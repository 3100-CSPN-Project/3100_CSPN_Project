create table if not exists public.game_comments (
  comment_id bigint generated by default as identity primary key,
  game_pk bigint not null references public.mlb_games(game_pk) on delete cascade,
  author text not null check (char_length(author) between 1 and 40),
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now()
);

create index if not exists game_comments_game_idx
  on public.game_comments (game_pk, created_at);

alter table public.game_comments enable row level security;

-- anyone can read and post until log in exists
create policy "Game comments are publicly readable"
  on public.game_comments for select to anon, authenticated using (true);

create policy "Anyone can post a game comment"
  on public.game_comments for insert to anon, authenticated with check (true);

grant select, insert on public.game_comments to anon, authenticated;
